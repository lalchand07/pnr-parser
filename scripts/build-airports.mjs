#!/usr/bin/env node
// Regenerates src/enrich/data/airports.ts from OurAirports (public domain).
//
//   node scripts/build-airports.mjs                 # download the latest CSVs
//   node scripts/build-airports.mjs airports.csv countries.csv   # use local files
//
// Source: https://ourairports.com/data/ — "All data is released to the Public Domain".
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const BASE = 'https://raw.githubusercontent.com/davidmegginson/ourairports-data/main';
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'enrich',
  'data',
  'airports.ts',
);

async function load(localPath, url) {
  if (localPath) return readFile(localPath, 'utf8');
  const res = await fetch(url);
  if (!res.ok) throw new Error(`GET ${url} -> ${res.status}`);
  return res.text();
}

/** Minimal RFC 4180 parser (quoted fields, doubled quotes, CRLF). */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else field += c;
  }
  if (field !== '' || row.length) {
    row.push(field);
    rows.push(row);
  }
  const [header, ...data] = rows;
  return data
    .filter((r) => r.length === header.length)
    .map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

const TYPE_RANK = { large_airport: 3, medium_airport: 2, small_airport: 1 };
const clean = (s) =>
  s
    .replace(/[\t\n\r]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const [airportsPath, countriesPath] = process.argv.slice(2);
const airports = parseCsv(await load(airportsPath, `${BASE}/airports.csv`));
const countries = parseCsv(await load(countriesPath, `${BASE}/countries.csv`));

const best = new Map();
for (const a of airports) {
  const iata = a.iata_code?.trim();
  if (!iata || !/^[A-Z]{3}$/.test(iata)) continue;
  const rank = TYPE_RANK[a.type];
  if (!rank) continue;
  // Small airports only when they have scheduled service.
  if (rank === 1 && a.scheduled_service !== 'yes') continue;
  const score = rank * 2 + (a.scheduled_service === 'yes' ? 1 : 0);
  const prev = best.get(iata);
  if (!prev || score > prev.score) best.set(iata, { score, a });
}

const countryName = new Map(countries.map((c) => [c.code, clean(c.name)]));
const usedCountries = new Set();
const lines = [...best.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([iata, { a }]) => {
    usedCountries.add(a.iso_country);
    return [iata, clean(a.name), clean(a.municipality ?? ''), a.iso_country].join('\t');
  });
const countryLines = [...usedCountries]
  .filter((c) => countryName.has(c))
  .sort()
  .map((c) => `${c}\t${countryName.get(c)}`);

const ts = `// GENERATED by scripts/build-airports.mjs — do not edit by hand.
// Source: OurAirports (https://ourairports.com/data/), released to the Public Domain.
// Generated: ${new Date().toISOString().slice(0, 10)}. ${lines.length} airports.
// Format: IATA<TAB>name<TAB>municipality<TAB>ISO country, one per line.
export const AIRPORTS_TSV = ${JSON.stringify(lines.join('\n'))};

// ISO 3166-1 alpha-2 code<TAB>country name (from OurAirports countries.csv).
export const COUNTRIES_TSV = ${JSON.stringify(countryLines.join('\n'))};
`;
await writeFile(OUT, ts);
console.log(`Wrote ${lines.length} airports and ${countryLines.length} countries to ${OUT}`);
